const { withDangerousMod } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

/**
 * NativeTabs on Android is a Material 3 BottomNavigationView, whose style pins
 * `android:minHeight` to `m3_bottom_nav_min_height` (80dp) — the height of an
 * icon + label item. With `native.tab_labels` off the bar kept that height, so
 * icons-only bars looked label-tall. Lowering the floor lets the bar take its
 * items' height: ~80dp with labels, less without (iOS already does this).
 * The system navigation inset is added on top as padding either way.
 */
const MIN_HEIGHT_DP = 56;
const FILE_NAME = 'neo_tab_bar_dimens.xml';

function withAndroidTabBarHeight(config) {
    return withDangerousMod(config, [
        'android',
        async (config) => {
            const valuesDir = path.join(config.modRequest.platformProjectRoot, 'app/src/main/res/values');
            fs.mkdirSync(valuesDir, { recursive: true });
            fs.writeFileSync(
                path.join(valuesDir, FILE_NAME),
                `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by apps/expo/plugins/with-android-tab-bar-height.js -->
<resources xmlns:tools="http://schemas.android.com/tools">
    <dimen name="m3_bottom_nav_min_height" tools:override="true">${MIN_HEIGHT_DP}dp</dimen>
</resources>
`
            );
            return config;
        },
    ]);
}

module.exports = withAndroidTabBarHeight;
