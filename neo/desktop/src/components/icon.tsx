export type IconName = keyof typeof ICONS;

/** A name from this set (commands.json names its icons as plain strings). */
export function isIconName(name: string): name is IconName {
    return Object.hasOwn(ICONS, name);
}

/** Icons that point along the reading direction: mirrored under a right-to-left locale. */
const FLIPS: ReadonlySet<IconName> = new Set(['chevron-left', 'chevron-right', 'panel-left', 'arrow-left-right', 'repeat-2']);

/** The SVG without its licence comment, fixed size and stroke: the CSS sizes it. */
function markup(name: IconName): string {
    return svgMarkup(ICONS[name]);
}

/** A Lucide SVG as this set draws it (site-icon.tsx draws the site's other Lucide icons with it). */
export function svgMarkup(raw: string): string {
    return raw
        .replace(/<!--[\s\S]*?-->/g, '')
        .replace(/\swidth="24"/, '')
        .replace(/\sheight="24"/, '')
        .replace(/\sstroke-width="2"/, '')
        .replace(/<svg/, '<svg focusable="false"')
        .trim();
}

const cache = new Map<IconName, string>();

type Props = {
    name: IconName;
    size?: 11 | 12 | 14 | 16 | 18 | 20 | 28 | 32;
    /** 2px strokes; ignored at 14px and under, where every icon has a 1px stroke. */
    strong?: boolean;
    /** Only for an icon that says something on its own (no text next to it, no named control around it). */
    label?: string;
};

export function Icon({ name, size = 16, strong, label }: Props) {
    let html = cache.get(name);
    if (html === undefined) {
        html = markup(name);
        cache.set(name, html);
    }
    // small icons (14px and under) draw a 1px stroke: 1.5 and 2px fill their shapes in at that size
    const small = size <= 14;
    const className = `icon${small ? ' icon-small' : strong ? ' icon-strong' : ''}${FLIPS.has(name) ? ' icon-flip' : ''}`;
    return (
        <span
            className={className}
            aria-hidden={label ? undefined : true}
            role={label ? 'img' : undefined}
            aria-label={label}
            data-icon={name}
            style={{ width: size, height: size }}
            dangerouslySetInnerHTML={{ __html: html }}
        />
    );
}
