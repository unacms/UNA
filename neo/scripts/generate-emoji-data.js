#!/usr/bin/env node
/**
 * Writes packages/app/lib/emoji/emoji-data.ts for the emoji picker from the
 * unicode-emoji-json package (a devDependency): every base emoji (no skin-tone
 * variants) up to MAX_EMOJI_VERSION, with its name, grouped as in Unicode.
 *
 *   node scripts/generate-emoji-data.js
 *
 * Newer emoji show as empty boxes on phones that haven't updated their OS, so
 * raise MAX_EMOJI_VERSION only when most devices support that version.
 */
const fs = require('fs');
const path = require('path');

const MAX_EMOJI_VERSION = 15.0;
const OUT = path.join(__dirname, '..', 'packages', 'app', 'lib', 'emoji', 'emoji-data.ts');

const groups = require('unicode-emoji-json/data-by-group.json');
const { version } = require('unicode-emoji-json/package.json');

const out = groups
    .filter((group) => group.slug !== 'component')
    .map((group) => ({
        id: group.slug,
        title: group.name,
        emojis: group.emojis
            .filter((e) => parseFloat(e.emoji_version) <= MAX_EMOJI_VERSION)
            .map((e) => [e.emoji, e.name]),
    }))
    .filter((group) => group.emojis.length > 0);

const count = out.reduce((n, group) => n + group.emojis.length, 0);

/** One emoji per line, so a data update reads as a readable diff. */
function formatGroup(group) {
    const emojis = group.emojis.map((entry) => `            ${JSON.stringify(entry)},`).join('\n');
    return `    {\n        id: ${JSON.stringify(group.id)},\n        title: ${JSON.stringify(group.title)},\n        emojis: [\n${emojis}\n        ],\n    },`;
}

const body = `// Generated by scripts/generate-emoji-data.js from unicode-emoji-json ${version}. Do not edit.
// ${count} emoji up to Emoji ${MAX_EMOJI_VERSION.toFixed(1)}, without skin-tone variants.

export type EmojiEntry = readonly [emoji: string, name: string];

export type EmojiGroup = {
    id: string;
    title: string;
    emojis: readonly EmojiEntry[];
};

export const EMOJI_GROUPS: readonly EmojiGroup[] = [
${out.map(formatGroup).join('\n')}
];
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body);
console.log(`${path.relative(process.cwd(), OUT)}: ${out.length} groups, ${count} emoji, ${Math.round(body.length / 1024)} KB`);
